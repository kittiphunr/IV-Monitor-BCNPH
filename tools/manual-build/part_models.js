// ---------------------------------------------------------------- ตัวช่วยนับเลข
const TH = '๐๑๒๓๔๕๖๗๘๙';
const thai = (n) => String(n).replace(/\d/g, (c) => TH[c]);

let tableNo = 19;
let figNo = 13;
const tocList = [];        // บรรทัดสารบัญของบทในไฟล์นี้ { text, level }
const tableList = [];      // บรรทัดสารบัญตาราง
const figureList = [];     // บรรทัดสารบัญภาพ

function tcap(title) {
  const t = 'ตารางที่ ' + thai(tableNo++) + '  ' + title;
  tableList.push(t);
  return tableCaption(t);
}
function fcap(title) {
  const t = 'ภาพที่ ' + thai(figNo++) + '  ' + title;
  figureList.push(t);
  return caption(t);
}

// หัวบทและหัวข้อที่นับเลขเอง
let chNo = '', secNo = 0;
function chap(no, title) {
  chNo = no; secNo = 0;
  tocList.push({ text: 'บทที่ ' + no + '  ' + title, level: 0 });
  return chapter(no, title);
}
function sec(title) {
  secNo++;
  const t = chNo + '.' + thai(secNo) + ' ' + title;
  tocList.push({ text: t, level: 1 });
  return h2(t);
}
let caseNo = 0;
function cs(title) {             // หัวข้อเคส: "เคสที่ n ..." นับใหม่ทุกบท
  caseNo++;
  return sec('เคสที่ ' + thai(caseNo) + '  ' + title);
}
function beginChapter(no, title) { caseNo = 0; return chap(no, title); }

// บรรทัดหัวเรื่องย่อยในเคส เช่น "สิ่งที่เห็นบนจอ"
function lab(label, text) {
  return new Paragraph({
    spacing: { after: 50, line: 240, lineRule: d.LineRuleType.AUTO },
    indent: { left: convertInchesToTwip(0.4) },
    children: [run(label + '  ', { bold: true }), ...L.runsFrom(text)],
  });
}
const step = (m, t) => item(m, t);
const gap = (n = 80) => plain('', { after: n });

// ภาพหลายรูปเรียงกันในแถวเดียว คำใต้ภาพย่อยไม่ใช้สไตล์คำบรรยาย
// เพื่อไม่ให้ไปปนในสารบัญภาพ (สารบัญภาพเก็บเฉพาะคำบรรยายรวมใต้แถว)
function imgRow(items, w, h) {
  const none = { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' };
  const bd = { top: none, bottom: none, left: none, right: none, insideHorizontal: none, insideVertical: none };
  const cw = Math.round(CONTENT_DXA / items.length);
  const mk = (it) => new TableCell({
    width: { size: cw, type: WidthType.DXA }, borders: bd,
    children: [img(it.file, w, h),
      new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 40, after: 60 },
                      children: [run(it.cap, { size: 26 })] })],
  });
  return new Table({ columnWidths: items.map(() => cw), width: { size: CONTENT_DXA, type: WidthType.DXA },
                     borders: bd, rows: [new TableRow({ cantSplit: true, children: items.map(mk) })] });
}

